const VIDEO_DIALOGUE_POLICY = 'iwantcheckmate'

function videoVariant({
  id,
  name,
  rating = null,
  country = 'United States',
  countryCode = 'us',
  category = null,
  avatar,
  avatarScale = null,
  avatarStates = null,
  identityStates = null,
  description,
  videoId,
  videoTitle,
  initialElo = 3600,
  minElo = 250,
  maxElo = 3600,
  trigger = null,
  eloDelta = 0,
  movePolicy = { type: 'best' },
  capabilities = {},
}) {
  const resolvedCategory = category
    || (id === 'iwc-smartin' || id.includes('martin') ? 'martin' : 'stockfish')
  const defaultAvatar = imageAvatar(
    name,
    avatar,
    avatarScale ?? 1,
  )
  const resolvedIdentityStates = identityStates
    ? Object.freeze(Object.fromEntries(
        Object.entries(identityStates).map(([state, identity]) => [
          state,
          Object.freeze({ ...identity }),
        ]),
      ))
    : null
  const resolvedAvatarStates = avatarStates
    ? Object.freeze(Object.fromEntries(
        Object.entries(avatarStates).map(([state, filename]) => [
          state,
          imageAvatar(resolvedIdentityStates?.[state]?.name || name, filename),
        ]),
      ))
    : null
  return Object.freeze({
    id,
    name,
    fullName: name,
    displayRating: rating,
    title: '',
    country,
    countryCode,
    category: resolvedCategory,
    avatar: defaultAvatar,
    avatarStates: resolvedAvatarStates,
    identityStates: resolvedIdentityStates,
    accounts: Object.freeze({ chesscom: [], lichess: [] }),
    intro: description,
    videoLabel: description,
    dialoguePolicy: VIDEO_DIALOGUE_POLICY,
    capabilities: Object.freeze({
      silentDialogue: false,
      videoVariant: true,
      beltMode: false,
      knightSpecialist: false,
      perfectTheory: false,
      maximumEngine: true,
      bishopKnightObjective: false,
      exactTablebase: false,
      ...capabilities,
    }),
    strengthPolicy: Object.freeze({
      engineElo: null,
      depth: 17,
      moveTime: 1150,
      candidates: 16,
      styleWindowCp: 0,
      bookWindowCp: 0,
      bookMinGames: Number.POSITIVE_INFINITY,
      bookMinRecentWeight: Number.POSITIVE_INFINITY,
      mateSafety: resolvedCategory === 'martin'
        ? Object.freeze({
            depth: 20,
            moveTime: 900,
            candidates: 1,
          })
        : null,
    }),
    repertoireSource: Object.freeze({
      chesscom: [],
      lichess: [],
      recentHalfLifeDays: 180,
    }),
    source: Object.freeze({
      channel: 'IWantCheckmate',
      videoId,
      videoTitle,
      videoUrl: `https://www.youtube.com/watch?v=${videoId}`,
    }),
    variant: Object.freeze({
      initialElo,
      minElo,
      maxElo,
      trigger,
      eloDelta,
      movePolicy: Object.freeze(movePolicy),
    }),
  })
}

function imageAvatar(name, filename, scale = 1) {
  return Object.freeze({
    type: 'image',
    src: `./assets/iwantcheckmate/${filename}`,
    alt: `${name} in-video profile`,
    objectPosition: '50% 50%',
    scale,
    transparent: true,
  })
}

